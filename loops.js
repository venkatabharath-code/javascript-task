// Example 1: for loop
for (let i = 1; i <= 5; i++) {
  console.log('Iteration ' + i);
}

// Example 2: while loop
let count = 0;
while (count < 3) {
  console.log('Count: ' + count);
  count++;
}

// Example 3: for...of loop
const fruits = ['Apple', 'Banana', 'Orange'];
for (const fruit of fruits) {
  console.log('Fruit: ' + fruit);
}
