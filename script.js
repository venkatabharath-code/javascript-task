// String + String = String Joining
alert("2" + "2"); // 22

// Number + Number = Addition
alert(2 + 6); // 8

// Joining Strings
alert("venkata" + " " + "Bharath"); // venkata Bharath

// Implicit Conversion
alert("4" - "1"); // 3

// + is used to join strings
// -, *, / work with numbers

// Explicit Conversion
let num = Number(10);
alert(num + 5); // 15

// Anything from prompt is treated as string
let age2 = Number(prompt("Enter your age"));

console.log(age2); // string value

// Convert string into number
let age3 = Number(prompt("Enter your age"));

alert(age3 + 5); // 5 is added to the age

